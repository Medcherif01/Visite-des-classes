export type UserRole = 'coordinator' | 'teacher' | 'admin';

export interface User {
  id: string;
  username: string;
  fullName: string;
  role: UserRole;
  email: string;
  password?: string;
  avatar?: string;
  department?: string;
  assignedTeachers?: string[]; // IDs or names of teachers assigned to coordinator
}

export interface CriterionItem {
  id: string;
  text_fr: string;
  text_ar: string;
  text_en: string;
  detail_fr: string;
  detail_ar: string;
  detail_en: string;
  maxPoints: number;
}

export interface GridCategory {
  id: string;
  title_fr: string;
  title_ar: string;
  title_en: string;
  maxPoints: number;
  items: CriterionItem[];
}

export interface EvaluationGrid {
  id: string;
  title: string;
  description: string;
  totalPoints: number;
  categories: GridCategory[];
  isDefault?: boolean;
}

export interface ObservationNote {
  id: string;
  timestamp: string; // e.g. "10:14"
  elapsedMinutes: number;
  content: string;
  tag: 'positif' | 'amelioration' | 'technique' | 'general';
}

export interface EvaluationVisit {
  id: string;
  teacherId: string;
  teacherName: string;
  coordinatorId: string;
  coordinatorName: string;
  schoolName: string;
  date: string;
  sessionNumber: number;
  className: string;
  subject: string;
  lessonTopic: string;
  studentCount?: number;
  gridId: string;
  gridTitle: string;
  ratings: Record<string, { rating: number; score: number }>; // criterionId -> rating (1-5) and calculated score
  categoryScores: Record<string, number>; // categoryId -> score sum
  grandTotal: number;
  maxPossibleScore: number;
  percentageScore: number;
  performanceLevel: {
    code: 'excellent' | 'very_good' | 'good' | 'satisfactory' | 'needs_improvement';
    label_fr: string;
    label_ar: string;
    label_en: string;
    color: string;
  };
  comments: {
    strengths: string;
    toImprove: string;
    recommendations: string;
    actionPlan?: string;
  };
  autoGeneratedReport?: string;
  observationNotes?: ObservationNote[];
  status: 'draft' | 'completed' | 'signed';
  syncStatus: 'synced' | 'pending';
  createdAt: string;
  updatedAt: string;
  teacherSignature?: {
    signed: boolean;
    date?: string;
    comment?: string;
  };
  coordinatorSignature?: {
    signed: boolean;
    date?: string;
  };
}

export interface SyncStats {
  pendingCount: number;
  lastSyncedAt: string | null;
  isOnline: boolean;
}
